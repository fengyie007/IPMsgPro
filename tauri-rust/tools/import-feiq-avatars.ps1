param([Parameter(Mandatory = $true)][string]$SourceDirectory)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$projectRoot = Split-Path -Parent $PSScriptRoot
$assetDirectory = Join-Path $projectRoot 'src\assets\feiq-avatars'
$items = @()
foreach ($id in 0..83) {
    $sourceFile = Join-Path $SourceDirectory ('BITMAP_' + ($id + 166) + '.bmp')
    $picture = [Drawing.Image]::FromFile($sourceFile)
    try {
        if ($picture.Width -lt 1 -or $picture.Width -gt 256 -or $picture.Height -lt 1 -or $picture.Height -gt 256) { throw "Invalid avatar dimensions: $id" }
        $items += [pscustomobject]@{ Id = $id; Source = $sourceFile; Width = $picture.Width; Height = $picture.Height }
    } finally { $picture.Dispose() }
}
[IO.Directory]::CreateDirectory($assetDirectory) | Out-Null
$imports = @('// Generated by tools/import-feiq-avatars.ps1; resources from PythonFeiQ static/headpic.')
foreach ($item in $items) {
    $picture = [Drawing.Bitmap]::new($item.Source)
    try {
        $destination = Join-Path $assetDirectory ($item.Id.ToString() + '.png')
        $picture.Save($destination, [Drawing.Imaging.ImageFormat]::Png)
        $decoded = [Drawing.Bitmap]::new($destination)
        try {
            foreach ($y in 0..($item.Height - 1)) {
                foreach ($x in 0..($item.Width - 1)) {
                    if ($picture.GetPixel($x, $y).ToArgb() -ne $decoded.GetPixel($x, $y).ToArgb()) { throw "Avatar pixel mismatch: $($item.Id)" }
                }
            }
        } finally { $decoded.Dispose() }
    } finally { $picture.Dispose() }
    $imports += "import avatar$($item.Id) from './assets/feiq-avatars/$($item.Id).png?url&no-inline';"
}
$imports += 'export const FEIQ_AVATAR_URLS: Readonly<Record<number, string>> = {'
foreach ($item in $items) { $imports += "  $($item.Id): avatar$($item.Id)," }
$imports += '};'
[IO.File]::WriteAllText((Join-Path $projectRoot 'src\feiqAvatarAssets.ts'), (($imports -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))
Write-Output 'Imported 84 avatars; converted PNG pixels match the source BMPs.'
