// Import the verified 96-entry mapping and GIF resources from CompileLife's feiq.
// Usage: node tools/import-feiq-emojis.cjs D:\sources\feiq
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const sourceRoot = process.argv[2];
if (!sourceRoot) throw new Error('Usage: node tools/import-feiq-emojis.cjs <feiq source directory>');
const source = fs.readFileSync(path.join(sourceRoot, 'emoji.cpp'), 'utf8');
function strings(name) {
  const body = source.match(new RegExp(`${name}\\[EMOJI_LEN\\]\\s*=\\s*\\{([\\s\\S]*?)\\};`));
  assert(body, `Missing ${name}`);
  return [...body[1].matchAll(/"(?:[^"\\]|\\.)*"/g)].map(([value]) => JSON.parse(value));
}
const codes = strings('g_emojis'), names = strings('g_emojiText');
assert.equal(codes.length, 96); assert.equal(names.length, 96);
assert.equal(new Set(codes).size, 96);
assert.equal(codes[0], '/:)'); assert.equal(names[0], '微笑');
const entries = codes.map((code, i) => {
  assert(/^\/[\x21-\x7e]+$/.test(code), `Invalid code ${code}`);
  const file = `${i + 1}.gif`;
  const bytes = fs.readFileSync(path.join(sourceRoot, 'res/face', file));
  assert(['GIF87a', 'GIF89a'].includes(bytes.subarray(0, 6).toString('ascii')));
  const width = bytes.readUInt16LE(6), height = bytes.readUInt16LE(8);
  assert(width > 0 && width <= 64 && height > 0 && height <= 64, `Invalid dimensions: ${file}`);
  return { metadata: { id: `feiq:${i + 1}`, name: names[i].trim(), code, file, width, height }, bytes };
});
const sourceDir = path.resolve(__dirname, '../src');
const assetsDir = path.join(sourceDir, 'assets/feiq');
fs.mkdirSync(assetsDir, { recursive: true });
for (const { metadata, bytes } of entries) fs.writeFileSync(path.join(assetsDir, metadata.file), bytes);
fs.writeFileSync(path.join(sourceDir, 'feiqEmojiData.ts'), [
  '// Generated by tools/import-feiq-emojis.cjs; source: CompileLife/feiq emoji.cpp.',
  '// IDs are ordinal and stable; display names are not unique.',
  'export interface FeiqEmojiDef { id: string; name: string; code: string; file: string; width: number; height: number }',
  'export const FEIQ_EMOJIS: readonly FeiqEmojiDef[] = [',
  ...entries.map(({ metadata }) => `  ${JSON.stringify(metadata)},`),
  '];', '',
].join('\n'));
fs.writeFileSync(path.join(sourceDir, 'feiqEmojiAssets.ts'), [
  '// Generated by tools/import-feiq-emojis.cjs. URLs are bundled, never external paths.',
  ...entries.map(({ metadata }, i) => `import emoji${i + 1} from './assets/feiq/${metadata.file}?url&no-inline';`),
  'export const FEIQ_EMOJI_URLS: Readonly<Record<string, string>> = {',
  ...entries.map(({ metadata }, i) => `  '${metadata.id}': emoji${i + 1},`),
  '};', '',
].join('\n'));
console.log(`Imported ${entries.length} original GIFs (${entries.reduce((sum, e) => sum + e.bytes.length, 0)} bytes).`);
